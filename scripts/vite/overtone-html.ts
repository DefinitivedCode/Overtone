import { createHash } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import type { HtmlTagDescriptor, Plugin } from 'vite';
import { splashLinks } from '../../src/app/splash-links.generated';

const CSP = (scriptHash: string) =>
  [
    "default-src 'self'",
    `script-src 'self' 'wasm-unsafe-eval' '${scriptHash}'`,
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data: blob:",
    "font-src 'self'",
    "connect-src 'self' https://lrclib.net",
    "worker-src 'self' blob:",
    "manifest-src 'self'",
    "base-uri 'none'",
    "form-action 'none'",
  ].join('; ');

/** Cloudflare Pages / Netlify `_headers`: the same CSP plus the protections a <meta> cannot carry, and caching. */
function headersFile(base: string, csp: string): string {
  const p = base.replace(/\/$/, '');
  return `/*
  Content-Security-Policy: ${csp}; frame-ancestors 'none'
  X-Content-Type-Options: nosniff
  Referrer-Policy: no-referrer
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=()
  Cross-Origin-Opener-Policy: same-origin

# Hashed build output never changes.
${p}/assets/*
  Cache-Control: public, max-age=31536000, immutable

# Language packs are versioned by path: <id>/<version>/<file>. The manifest next to them is not.
${p}/packs/:id/:version/*
  Cache-Control: public, max-age=31536000, immutable
`;
}

function manifest(base: string): string {
  return JSON.stringify(
    {
      id: base,
      name: 'Overtone',
      short_name: 'Overtone',
      description:
        'Learn to read, understand and sing lyrics in Korean, Japanese, Mandarin and Cantonese.',
      start_url: base,
      scope: base,
      display: 'standalone',
      orientation: 'any',
      background_color: '#F6F2EC',
      theme_color: '#F6F2EC',
      lang: 'en',
      categories: ['education', 'music'],
      icons: [
        { src: `${base}icons/icon-192.png`, sizes: '192x192', type: 'image/png', purpose: 'any' },
        { src: `${base}icons/icon-512.png`, sizes: '512x512', type: 'image/png', purpose: 'any' },
        {
          src: `${base}icons/maskable-512.png`,
          sizes: '512x512',
          type: 'image/png',
          purpose: 'maskable',
        },
      ],
    },
    null,
    2,
  );
}

/**
 * - emits a base-path-aware web app manifest (VITE_BASE support)
 * - injects apple-touch-startup-image links generated by `npm run brand`
 * - in production builds, injects a CSP <meta> whose script hash covers the inline theme script
 */
export function overtoneHtml(): Plugin {
  let base = '/';
  let isBuild = false;
  let csp = '';
  let outDir = 'dist';
  return {
    name: 'overtone-html',
    configResolved(config) {
      base = config.base;
      isBuild = config.command === 'build';
      outDir = path.resolve(config.root, config.build.outDir);
    },
    configureServer(server) {
      server.middlewares.use(`${base}manifest.webmanifest`, (_req, res) => {
        res.setHeader('Content-Type', 'application/manifest+json');
        res.end(manifest(base));
      });
    },
    generateBundle() {
      this.emitFile({ type: 'asset', fileName: 'manifest.webmanifest', source: manifest(base) });
    },
    // The HTML transform runs after generateBundle, so the headers file is written once the hash is known.
    closeBundle() {
      if (!isBuild || !csp) return;
      const dir = path.resolve(outDir);
      mkdirSync(dir, { recursive: true });
      writeFileSync(path.join(dir, '_headers'), headersFile(base, csp));
    },
    transformIndexHtml(html) {
      const tags: HtmlTagDescriptor[] = [
        {
          tag: 'link',
          attrs: { rel: 'manifest', href: `${base}manifest.webmanifest` },
          injectTo: 'head',
        },
        ...splashLinks.map((l): HtmlTagDescriptor => ({
          tag: 'link',
          attrs: { rel: 'apple-touch-startup-image', href: `${base}${l.href}`, media: l.media },
          injectTo: 'head',
        })),
      ];
      if (isBuild) {
        const m = /<script id="theme-init">([\s\S]*?)<\/script>/.exec(html);
        if (!m) throw new Error('index.html is missing <script id="theme-init">');
        const hash = `sha256-${createHash('sha256').update(m[1]!).digest('base64')}`;
        csp = CSP(hash);
        tags.unshift({
          tag: 'meta',
          attrs: { 'http-equiv': 'Content-Security-Policy', content: CSP(hash) },
          injectTo: 'head-prepend',
        });
      }
      return { html, tags };
    },
  };
}
