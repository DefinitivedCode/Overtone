import { createHash } from 'node:crypto';
import { existsSync } from 'node:fs';
import path from 'node:path';
import type { Plugin } from 'vite';
import { PACK_CACHE } from '../../src/engine/dict/types';

/** Public files that are not part of the Rollup bundle but are needed offline. */
const STATIC = [
  'manifest.webmanifest',
  'favicon.svg',
  'icons/apple-touch-icon.png',
  'icons/icon-192.png',
  'icons/icon-512.png',
  'icons/maskable-512.png',
  'fonts/instrument-serif-latin-400.woff2',
];

const PRECACHE_BUDGET = 2 * 1024 * 1024; // ARCHITECTURE §9, excluding packs
const PACK_MANIFEST = 'packs/manifest.json';

const template = (
  version: string,
  urls: string[],
) => `/* Overtone service worker — generated by scripts/vite/overtone-sw.ts. */
const VERSION = ${JSON.stringify(version)};
const PRECACHE = 'overtone-precache-' + VERSION;
const PACKS = ${JSON.stringify(PACK_CACHE)};
const SCOPE = self.registration.scope;
const URLS = ${JSON.stringify(urls)}.map((u) => new URL(u, SCOPE).href);
// The app shell is cached under the scope root ('./'): the HTML plugin may emit index.html after this plugin runs.
const INDEX = SCOPE;

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(PRECACHE).then((c) => c.addAll(URLS)));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k.startsWith('overtone-precache-') && k !== PRECACHE).map((k) => caches.delete(k))),
    ),
  );
});

// Static hosts add 'Vary: Origin'; a CORS font request would otherwise miss its own precached entry.
const MATCH = { ignoreVary: true };
const timeout = (ms) => new Promise((_, reject) => setTimeout(() => reject(new Error('timeout')), ms));
const remember = (event, cache, request, response) => {
  if (response.ok) event.waitUntil(cache.put(request, response.clone()).catch(() => undefined));
  return response;
};

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return; // lrclib etc. are never cached here

  // Language packs: cache-first, managed from Settings (no automatic expiry).
  if (url.pathname.startsWith(new URL('packs/', SCOPE).pathname)) {
    const isManifest = url.pathname.endsWith('/manifest.json');
    event.respondWith(
      (async () => {
        const cache = await caches.open(PACKS);
        if (isManifest) {
          try {
            return remember(event, cache, req, await fetch(req, { cache: 'no-cache' }));
          } catch (e) {
            const hit = (await cache.match(req, MATCH)) ?? (await caches.match(req, MATCH));
            if (hit) return hit;
            throw e;
          }
        }
        const hit = await cache.match(req, MATCH);
        if (hit) return hit;
        return remember(event, cache, req, await fetch(req));
      })(),
    );
    return;
  }

  // Navigations: network first (3 s), then the precached app shell (SPA fallback).
  if (req.mode === 'navigate') {
    event.respondWith(
      Promise.race([fetch(req), timeout(3000)]).catch(async () => (await caches.match(INDEX, MATCH)) ?? Response.error()),
    );
    return;
  }

  // Everything else from the app: precache first, then network (hashed lazy chunks are cached on first use).
  event.respondWith(
    (async () => {
      const hit = await caches.match(req, MATCH);
      if (hit) return hit;
      const res = await fetch(req);
      if (res.ok && url.pathname.includes('/assets/')) {
        const copy = res.clone();
        event.waitUntil(caches.open(PRECACHE).then((cache) => cache.put(req, copy)).catch(() => undefined));
      }
      return res;
    })(),
  );
});
`;

/** Emits `sw.js` listing every built file, and fails the build if the precache exceeds its budget. */
export function overtoneServiceWorker(): Plugin {
  let publicDir = '';
  return {
    name: 'overtone-sw',
    apply: 'build',
    configResolved(config) {
      publicDir = config.publicDir;
    },
    generateBundle(_opts, bundle) {
      const files = Object.keys(bundle).filter((f) => !f.endsWith('.map') && f !== 'sw.js');
      let bytes = 0;
      for (const f of files) {
        const o = bundle[f]!;
        bytes +=
          o.type === 'chunk'
            ? Buffer.byteLength(o.code)
            : Buffer.byteLength(o.source as string | Uint8Array);
      }
      if (bytes > PRECACHE_BUDGET)
        this.warn(
          `Precache is ${(bytes / 1048576).toFixed(2)} MB of built JS/CSS/HTML (budget 2 MB, ARCHITECTURE §9).`,
        );
      const urls = [...new Set(['./', ...files, ...STATIC])]; // addAll rejects duplicates
      if (publicDir && existsSync(path.join(publicDir, PACK_MANIFEST))) urls.push(PACK_MANIFEST);
      const version = createHash('sha1').update(template('', urls)).digest('hex').slice(0, 10);
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: template(version, urls) });
    },
  };
}
