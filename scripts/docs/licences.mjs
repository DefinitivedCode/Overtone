// Generates src/features/about/licences.generated.ts from package metadata and the pinned dictionary sources.
// Run `npm run licences` after changing dependencies or scripts/packs/sources.json.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..', '..');
const read = (p) => JSON.parse(readFileSync(path.join(root, p), 'utf8'));
const pkg = read('package.json');
const sources = read('scripts/packs/sources.json');

// Runtime dependencies plus the fonts that are bundled into the build.
const names = [
  ...Object.keys(pkg.dependencies),
  ...Object.keys(pkg.devDependencies).filter((n) => n === '@fontsource/instrument-serif'),
].sort();

const licenceOf = (meta) =>
  typeof meta.license === 'string'
    ? meta.license
    : (meta.license?.type ?? meta.licenses?.map((l) => l.type).join(' OR ') ?? 'See package');

const packages = names.map((name) => {
  const meta = read(`node_modules/${name}/package.json`);
  return { name, version: meta.version, licence: licenceOf(meta) };
});

const dictionaries = Object.values(sources.sources).map((s) => ({
  name: s.name,
  licence: s.licence,
  attribution: s.attribution,
  url: s.url,
}));

const body = `// Generated by scripts/docs/licences.mjs — do not edit.
export interface PackageLicence {
  name: string;
  version: string;
  licence: string;
}
export interface DictionarySource {
  name: string;
  licence: string;
  attribution: string;
  url: string;
}

export const PACKAGE_LICENCES: readonly PackageLicence[] = ${JSON.stringify(packages, null, 2)};

export const DICTIONARY_SOURCES: readonly DictionarySource[] = ${JSON.stringify(dictionaries, null, 2)};
`;
writeFileSync(path.join(root, 'src/features/about/licences.generated.ts'), body);
console.log(`${packages.length} packages, ${dictionaries.length} dictionary sources`);
